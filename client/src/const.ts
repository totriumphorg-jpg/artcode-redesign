export const getLoginUrl = (redirectUri?: string) => {
  const portalUrl = import.meta.env.VITE_OAUTH_PORTAL_URL;
  const appId = import.meta.env.VITE_APP_ID;

  if (!portalUrl || !appId) {
    return "/";
  }

  const targetRedirectUri =
    redirectUri ||
    (typeof window !== "undefined"
      ? `${window.location.origin}/api/oauth/callback`
      : "");

  const state = encodeOAuthState({
    redirectUri: targetRedirectUri,
  });

  if (typeof document !== "undefined") {
    document.cookie = `${OAUTH_STATE_COOKIE}=${encodeURIComponent(
      state
    )}; path=/; max-age=600; SameSite=Lax`;
  }

  const url = new URL(portalUrl);
  url.searchParams.set("app_id", appId);
  url.searchParams.set("state", state);
  url.searchParams.set("redirect_uri", targetRedirectUri);

  return url.toString();
};

export const startLogin = (redirectUri?: string) => {
  const url = getLoginUrl(redirectUri);
  if (typeof window !== "undefined") {
    window.location.href = url;
  }
};

